/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM2_Init();
  MX_I2C1_Init();
  MX_TIM1_Init();
  /* USER CODE BEGIN 2 */
  HAL_TIM_Encoder_Start(&htim2, TIM_CHANNEL_1);
  HAL_TIM_Encoder_Start(&htim2, TIM_CHANNEL_2);

  my_lcd.hi2c = &hi2c1;
  my_lcd.address = 0x27 << 1;  // địa chỉ LCD (nhân 2 vì HAL dùng 8-bit addr)
  lcd_init(&my_lcd);
  lcd_clear(&my_lcd);

  // Start PWM with initial duty cycle
   HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
   update_duty_cycle();

   // Set motor direction
   HAL_GPIO_WritePin(GPIOA, GPIO_PIN_9, GPIO_PIN_SET);   // IN1 = 1
   HAL_GPIO_WritePin(GPIOA, GPIO_PIN_10, GPIO_PIN_RESET); // IN2 = 0
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  	  encoder = __HAL_TIM_GET_COUNTER(&htim2);
	  	  time_now = HAL_GetTick();
	  	  int16_t delta_encoder = encoder - encoder_prev;
	  	  uint32_t delta_time = time_now - time_prev;
	  	  if (delta_time > 0)
	  	  {
	  	      // Vận tốc v = [(delta_encoder / PULSES_PER_REV) / (delta_time / 1000)] * (π * D)
	  	      velocity = ((float)delta_encoder / PULSES_PER_REV) / (delta_time / 1000.0f) * (PI * WHEEL_DIAMETER);
	  	  }

	  	  encoder_prev = encoder;
	  	  time_prev = time_now;

	  	  lcd_gotoxy(&my_lcd, 0, 0);
	  	  sprintf(buffer, "Enc: %5d   ", encoder);
	  	  lcd_puts(&my_lcd, buffer);

	  	  lcd_gotoxy(&my_lcd, 0, 1);
	  	  sprintf(buffer, "v=%.2f m/s ", velocity);
	  	  lcd_puts(&my_lcd, buffer);

	  	  HAL_Delay(500);

	  	// Update duty cycle every 5 seconds
	  	      HAL_Delay(DUTY_CYCLE_UPDATE_INTERVAL);

	  	      // Increase duty cycle by 10%
	  	      current_duty_cycle += DUTY_CYCLE_INCREMENT;
	  	      if(current_duty_cycle > MAX_DUTY_CYCLE) {
	  	        current_duty_cycle = INITIAL_DUTY_CYCLE; // Reset to 20% if exceeds 100%
	  	      }

	  	      // Update PWM duty cycle
	  	      update_duty_cycle();
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

